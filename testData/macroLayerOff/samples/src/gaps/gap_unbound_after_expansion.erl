%% Известный пробел плагина: ошибка видна только после раскрытия.
%% Тело USE использует переменную X, а в `f/0` её нет.
%% erlc отвергает файл:
%% erlc: gap_unbound_after_expansion.erl:17:4: variable 'X' is unbound
%% Плагин эту ошибку не показывает: в тексте `f/0` переменной X нет.
%%
%% Что попробовать:
%% 1. Посмотри на `?USE` в `f/0`. По erlc тут должно быть красное.
%% 2. В `g/1` та же переменная есть, и ошибки нет.
-module(gap_unbound_after_expansion).

-export([f/0, g/1]).

-define(USE, X + 1).

f() ->
  ?USE.

g(X) ->
  ?USE.
