%% Известный пробел плагина: `?PAR(1)`, когда PAR есть только без
%% аргументов. erlc принимает файл: он берёт PAR без аргументов, а `(1)`
%% остаётся обычным текстом. `foo?PAR(1)` становится `foo()(1)`: вызов
%% fun, которую вернула foo().
%% Плагин этот случай не поддерживает. Красное здесь было бы ложным.
%%
%% Что попробовать:
%% 1. Посмотри, есть ли красное на `?PAR(1)` в `call/0`. Его быть не должно.
%% 2. Поставь курсор на `PAR` в `?PAR(1)` и нажми Cmd+B. Должно открыться
%%    `-define(PAR, ()).`
-module(gap_par_with_args).

-export([call/0]).

-define(PAR, ()).

call() ->
  foo?PAR(1).

foo() ->
  fun(X) -> X + 1 end.
