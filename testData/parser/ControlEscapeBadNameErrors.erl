-module('ControlEscapeBadNameErrors').

s1() -> "\^"".
s1_ok() -> "\^\".

s2() -> "a\^"b".
s2_ok() -> "a\^\" ++ "b".

s3() -> "\^"" ++ "b".

g1() -> ~"\^"".
g1_ok() -> ~"\^\".

g2() -> ~s(\^)).
g2_ok() -> ~s(\^\).

g3() -> ~b<\^>>.
g3_ok() -> ~b<\^\>.

g4() -> ~s/\^//.
g4_ok() -> ~s/\^\/.

g5() -> ~s'\^''.
g5_ok() -> ~s'\^\'.

g6() -> ~s{\^}}.
g6_ok() -> ~s{\^\}.

after_literals() -> {ok, 'atom', "c"}.
