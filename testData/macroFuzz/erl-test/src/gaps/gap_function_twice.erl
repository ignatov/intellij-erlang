%% Известный пробел плагина: функция объявлена дважды. Первый раз её
%% делает макрос `?DEF(hello).`, второй раз она написана руками.
%% erlc отвергает файл:
%% erlc: gap_function_twice.erl:19:1: function hello/0 already defined
%% Плагин эту ошибку не показывает.
%%
%% Что попробовать:
%% 1. Посмотри на второе `hello() -> ok.` По erlc тут должно быть красное.
%% 2. Поставь курсор на `hello` в `f/0` и нажми Cmd+B. Посмотри, какие
%%    определения предложит плагин.
-module(gap_function_twice).

-export([f/0]).

-define(DEF(Name), Name() -> ok).

?DEF(hello).

hello() -> ok.

f() ->
  hello().
