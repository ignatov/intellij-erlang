%% Известный пробел плагина: `??Y`, где Y не параметр макроса.
%% erlc не делает из этого строку. Он отбрасывает `??` и оставляет
%% переменную Y. В `f/0` переменной Y нет, и erlc отвергает файл:
%% erlc: gap_stringify_non_param.erl:17:4: variable 'Y' is unbound
%% Плагин эту ошибку не показывает.
%%
%% Что попробовать:
%% 1. Посмотри на `?S(1)` в `f/0`. По erlc тут должно быть красное.
%% 2. Поставь курсор на `S` и нажми Cmd+B.
-module(gap_stringify_non_param).

-export([f/0]).

-define(S(X), ??Y).

f() ->
  ?S(1).
